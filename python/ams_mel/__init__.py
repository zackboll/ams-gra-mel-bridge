"""Safe Python sessions, IR Image/Stacked/C2/Instrumentation/Health, and RF Admin.

Public modules group the interface by domain: ams_mel.common for shared values
and errors, ams_mel.ir for IR sessions/channels, and ams_mel.rf for RF Admin.
Use ``from ams_mel import common, ir, rf`` or import names from those modules.
The original flat imports remain supported with identical objects and pickle
paths. Every import spelling retains the native facade loading requirement.

Session discovery returns complete owned capability snapshots without attaching
channels. ImageStream supports host-memory Mono8 acquisition or a control-only
attachment, plus explicit navigation submission and independent metadata
receivers. StackedImage provides attachment, enablement and common services;
stacked acquisition is not exposed. RFAdmin uses an independent provider factory.

IR C2 provides asynchronous :class:`ModeRequest` and :class:`ReturnRequest`
owners. BIT support is limited to the empty/no-op profile; payload-bearing BIT
execution is not exposed. C2 metadata independently receives CommandStatus,
BIT configuration and canonical Health BitStatus, plus separately opt-in
CommsTest reports. Request timeout and close do not cancel provider work.

Common Channel: :meth:`ControlChannel.channel_view`,
:meth:`ImageStream.channel_view`, :meth:`InstrumentationChannel.channel_view`,
:meth:`HealthStatusChannel.channel_view`, and :meth:`StackedChannel.channel_view`
return a weak :class:`ChannelView` offering
the inherited KeepAlive (the existing :class:`ReturnRequest`), CommsTest
(:class:`CommsRequest`), and a complete Python-owned
:class:`ChannelCapability`. A Python ``ChannelView`` owns only the native
``ams_mel_ir_channel`` weak-view wrapper, and that native view owns only weak
family state: keeping a View alive keeps no typed owner, Session, provider
channel, or provider library alive, and the View holds no reference to its
Python source. After the source is torn down the View is still open (it still
owns its wrapper) but channel operations fail with ``PROVIDER_FAILED``;
closing the weak wrapper remains independent of the source channel.

Operations using one owner must follow the native external-serialization
contract. At most one receive operation may consume an :class:`ImageStream` at
a time. The GIL is not a substitute for either contract; this API does not
claim that owners are thread-safe. Wait must not race the corresponding request
close, and control enable, submission operations, and close require
external serialization. Operations and close on one :class:`ChannelView`
require external serialization (distinct Views need none), and Wait and close
on one :class:`ReturnRequest` or :class:`CommsRequest` require external
serialization. Instrumentation enable, submit, metadata open, capabilities,
view conversion, and close on one channel also require serialization, as do Wait
and close on one InstrumentationRequest. Receive, counters, and close on one
InstrumentationMetadata require external serialization. No Python lock or worker
thread is added. Health enable, metadata open, capabilities, view conversion,
and close on one owner likewise require external serialization, as do receive,
counters and close on one HealthMetadataStream. Image/Health open_nuc is
independently opt-in; receive, counters and close on one NucStream likewise
require external serialization. No Python parent is retained by NucStream.
C2 metadata operations and Close, and registration versus parent C2 operations,
likewise require external serialization. C2MetadataStream retains no Python
parent; Close does not unregister callbacks, cancel requests or promise quiescence.
"""

